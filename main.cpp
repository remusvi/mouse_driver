uint8_t calculate_mouse_checksum(const uint8_t* packet, size_t length) {
    uint8_t sum = 0;

    // Sum all bytes up to index 11, but skip index 11 entirely
    for (size_t i = 0; i < 11; i++) {
        sum += packet[i];
    }

    // The firmware subtracts a static offset of 0x15 (21 decimal)
    return sum - 0x15;
}

uint8_t calculate_dpi_checksum(const uint8_t* packet, size_t length) {
    uint8_t sum = 0;


    for (size_t i = 0; i < 26; i++) {
        sum += packet[i];
    }


    return sum - 0x15;
};

